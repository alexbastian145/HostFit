package com.hostfit.core;

/**
 * What the user wants to host, together with the workload profile used by
 * {@link CapacityEstimator}. The numbers are deliberately simple, explainable
 * rules of thumb (not machine learning) so every recommendation can be traced.
 */
public enum UseCase {
    //            label              description                                   pages  MB/pg  visits/vCPU  visits/GB-RAM  baseRam  sharedCeiling
    BLOG("Blog / content site", "WordPress or static blog, mostly cached reads", 2.2, 0.8, 80_000, 100_000, 0.5, 100_000),
    WEBSITE("Business website", "Company or portfolio site with a CMS", 2.5, 1.2, 60_000, 80_000, 0.5, 50_000),
    ECOMMERCE("E-commerce store", "Online shop (WooCommerce, Magento, custom)", 5.0, 1.5, 30_000, 25_000, 1.5, 20_000),
    APP_BACKEND("App / API backend", "Backend for a mobile or web application", 25.0, 0.3, 20_000, 15_000, 1.0, 0),
    DATABASE("Database server", "MySQL / PostgreSQL / MongoDB for your own apps", 40.0, 0.2, 20_000, 40_000, 1.0, 0);

    private final String label;
    private final String description;
    private final double pagesPerVisit;
    private final double pageWeightMb;
    private final long visitsPerVcpu;
    private final long visitsPerGbRam;
    private final double baseRamGb;
    private final long sharedVisitCeiling;

    UseCase(String label, String description, double pagesPerVisit, double pageWeightMb,
            long visitsPerVcpu, long visitsPerGbRam, double baseRamGb, long sharedVisitCeiling) {
        this.label = label;
        this.description = description;
        this.pagesPerVisit = pagesPerVisit;
        this.pageWeightMb = pageWeightMb;
        this.visitsPerVcpu = visitsPerVcpu;
        this.visitsPerGbRam = visitsPerGbRam;
        this.baseRamGb = baseRamGb;
        this.sharedVisitCeiling = sharedVisitCeiling;
    }

    public String getLabel() {
        return label;
    }

    public String getDescription() {
        return description;
    }

    /** Average page views (or API calls / queries) generated by one visit. */
    public double getPagesPerVisit() {
        return pagesPerVisit;
    }

    /** Average transferred megabytes per page view after browser/CDN caching. */
    public double getPageWeightMb() {
        return pageWeightMb;
    }

    public long getVisitsPerVcpu() {
        return visitsPerVcpu;
    }

    public long getVisitsPerGbRam() {
        return visitsPerGbRam;
    }

    public double getBaseRamGb() {
        return baseRamGb;
    }

    /** Highest monthly visit count for which shared hosting is still sensible; 0 = shared hosting never suitable. */
    public long getSharedVisitCeiling() {
        return sharedVisitCeiling;
    }
}
